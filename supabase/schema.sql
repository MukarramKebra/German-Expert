-- ============================================================================
-- German Expert (Sharjah) — full database schema, single source of truth.
--
-- Rebuilt on 2026-11-08 from the LIVE schema of the Expert Hardware Kuwait
-- project this store was forked from (not from its old SQL files, which had
-- drifted and granted anon write). Run once on an empty Supabase project.
--
-- Deliberate differences vs the Kuwait live DB:
--   * money columns are numeric(10,2) (AED, 2 decimals) instead of (10,3)
--   * expert_analytics has no anon UPDATE policy (writes go via the RPC)
--   * expert_reviews inserts are length/rating bounded; admins may moderate
--   * increment_expert_analytics clamps each call to +10 (storefront sends +1)
--   * expert_orders.short_code is UNIQUE (it's the public lookup key)
--   * dead tables expert_admin_accounts / expert_admin_master and the unused
--     get_order_by_id() RPC are not recreated
--
-- Security model:
--   * anon (public storefront key) can only SELECT catalog/site tables.
--   * Admin writes need an authenticated Supabase Auth user with a row in
--     expert_admin_profiles (is_admin()). Accounts are created only through
--     the `admin-manage-accounts` Edge Function (service role).
--   * Guests place orders via INSERT (no read-back); order lookup goes through
--     get_order_by_code(); stock changes only via decrement_stock().
-- ============================================================================

