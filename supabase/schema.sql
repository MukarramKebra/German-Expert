-- ── Helper functions ───────────────────────────────────────────────────────
create or replace function public.is_admin(uid uuid)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from expert_admin_profiles where id = uid);
$$;

create or replace function public.has_admin_perm(p_tab text, p_edit boolean)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from expert_admin_profiles p
    where p.id = auth.uid()
      and (p.role <> 'custom'
           or (p.permissions -> p_tab ->> (case when p_edit then 'edit' else 'view' end)) = 'true')
  );
$$;

-- ── Storefront RPCs (anon-callable on purpose) ─────────────────────────────
create or replace function public.increment_expert_analytics(p_id bigint, p_views integer, p_searches integer)
returns void language sql security definer set search_path to 'public' as $$
  insert into public.expert_analytics (product_id, views, searches)
  values (p_id, greatest(0, least(coalesce(p_views,0), 10)), greatest(0, least(coalesce(p_searches,0), 10)))
  on conflict (product_id) do update
    set views    = public.expert_analytics.views    + excluded.views,
        searches = public.expert_analytics.searches + excluded.searches;
$$;

-- Can only ever subtract stock; per-call cap = expert_settings.max_order_qty (default 1000)
create or replace function public.decrement_stock(p_product_id bigint, p_qty integer)
returns void language plpgsql security definer set search_path to 'public' as $$
declare v_cap integer;
begin
  select case when value ~ '^[0-9]{1,6}$' then value::integer end
    into v_cap from expert_settings where key = 'max_order_qty';
  if v_cap is null or v_cap < 1 then v_cap := 1000; end if;
  if p_qty is null or p_qty < 1 or p_qty > v_cap then
    raise exception 'invalid qty' using errcode = '22023';
  end if;
  insert into expert_stock (product_id, qty)
  values (p_product_id, greatest(0, 50 - p_qty))
  on conflict (product_id) do update
    set qty = greatest(0, expert_stock.qty - p_qty);
end; $$;

create or replace function public.get_order_by_code(p_code text)
returns table(id uuid, status text, total numeric, created_at timestamptz, items text, address text, short_code text)
language sql stable security definer set search_path to 'public' as $$
  select o.id, o.status, o.total, o.created_at, o.items, o.address, o.short_code
  from expert_orders o
  where o.short_code = upper(btrim(p_code)) or o.id::text = lower(btrim(p_code))
  limit 1;
$$;

create or replace function public.cancel_order(p_id uuid)
returns boolean language plpgsql security definer set search_path to 'public' as $$
declare v_count int;
begin
  update expert_orders set status = 'cancelled'
  where id = p_id and status not in ('cancelled','delivered')
    and now() - created_at < interval '1 hour';
  get diagnostics v_count = row_count;
  return v_count > 0;
end; $$;

-- ── Admin RPCs ─────────────────────────────────────────────────────────────
create or replace function public.admin_list_orders()
returns setof expert_orders language plpgsql security definer set search_path to 'public' as $$
begin
  if not is_admin(auth.uid()) then raise exception 'not authorized' using errcode = '28000'; end if;
  if not has_admin_perm('orders', false) then return; end if;
  return query select * from expert_orders order by created_at desc;
end; $$;

create or replace function public.admin_update_order_status(p_id uuid, p_status text)
returns void language plpgsql security definer set search_path to 'public' as $$
begin
  if not is_admin(auth.uid()) then raise exception 'not authorized' using errcode = '28000'; end if;
  if not has_admin_perm('orders', true) then raise exception 'not authorized' using errcode = '28000'; end if;
  if p_status not in ('pending','confirmed','delivered','cancelled') then
    raise exception 'invalid status: %', p_status;
  end if;
  update expert_orders set status = p_status where id = p_id;
end; $$;

create or replace function public.admin_delete_order(p_id uuid)
returns void language plpgsql security definer set search_path to 'public' as $$
begin
  if not is_admin(auth.uid()) then raise exception 'not authorized' using errcode = '28000'; end if;
  if not has_admin_perm('orders', true) then raise exception 'not authorized' using errcode = '28000'; end if;
  delete from expert_orders where id = p_id;
end; $$;

-- ── Function privileges (PUBLIC gets EXECUTE by default — strip it) ────────
revoke execute on function public.is_admin(uuid), public.has_admin_perm(text, boolean),
  public.admin_list_orders(), public.admin_update_order_status(uuid, text),
  public.admin_delete_order(uuid), public.increment_expert_analytics(bigint, integer, integer),
  public.decrement_stock(bigint, integer), public.get_order_by_code(text),
  public.cancel_order(uuid), public.items_json_ok(text)
  from public;
grant execute on function public.increment_expert_analytics(bigint, integer, integer),
  public.decrement_stock(bigint, integer), public.get_order_by_code(text),
  public.cancel_order(uuid), public.items_json_ok(text), public.is_admin(uuid)
  to anon, authenticated;
grant execute on function public.has_admin_perm(text, boolean), public.admin_list_orders(),
  public.admin_update_order_status(uuid, text), public.admin_delete_order(uuid)
  to authenticated;

