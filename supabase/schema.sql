-- Catalog/site tables + analytics: public read, admin write
do $$
declare t text;
begin
  foreach t in array array['expert_products','expert_stock','expert_photos','expert_hidden',
                           'expert_cat_bgs','expert_banners','expert_settings','expert_analytics'] loop
    execute format('drop policy if exists %I on public.%I', t||'_public_select', t);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)', t||'_public_select', t);
    execute format('drop policy if exists %I on public.%I', t||'_admin_all', t);
    execute format('create policy %I on public.%I for all to authenticated using (is_admin(auth.uid())) with check (is_admin(auth.uid()))', t||'_admin_all', t);
  end loop;
end $$;

-- Reviews: public read + bounded insert, admins can moderate
drop policy if exists expert_reviews_select on public.expert_reviews;
create policy expert_reviews_select on public.expert_reviews for select to anon, authenticated using (true);
drop policy if exists expert_reviews_insert on public.expert_reviews;
create policy expert_reviews_insert on public.expert_reviews for insert to anon, authenticated
  with check (rating between 1 and 5 and length(coalesce(name,'')) <= 100 and length(coalesce(comment,'')) <= 2000);
drop policy if exists expert_reviews_admin_all on public.expert_reviews;
create policy expert_reviews_admin_all on public.expert_reviews for all to authenticated
  using (is_admin(auth.uid())) with check (is_admin(auth.uid()));

-- Customers: own row only
drop policy if exists expert_customers_own on public.expert_customers;
create policy expert_customers_own on public.expert_customers for all to authenticated
  using (auth.uid() = id) with check (auth.uid() = id);

-- Orders: guests insert-only, signed-in shoppers insert/read their own
drop policy if exists expert_orders_anon_insert on public.expert_orders;
create policy expert_orders_anon_insert on public.expert_orders for insert to anon with check (
  user_id is null and status = 'pending' and notified = false
  and coalesce(total,0) >= 0 and coalesce(total,0) < 1000000
  and length(coalesce(customer_name,'')) <= 200 and length(coalesce(customer_phone,'')) <= 40
  and length(coalesce(customer_email,'')) <= 254 and length(coalesce(address,'')) <= 1000
  and length(coalesce(notes,'')) <= 2000 and length(coalesce(items,'')) <= 100000);
drop policy if exists expert_orders_own_insert on public.expert_orders;
create policy expert_orders_own_insert on public.expert_orders for insert to authenticated with check (
  auth.uid() = user_id and status = 'pending' and notified = false
  and coalesce(total,0) >= 0 and coalesce(total,0) < 1000000
  and length(coalesce(customer_name,'')) <= 200 and length(coalesce(customer_phone,'')) <= 40
  and length(coalesce(customer_email,'')) <= 254 and length(coalesce(address,'')) <= 1000
  and length(coalesce(notes,'')) <= 2000 and length(coalesce(items,'')) <= 100000);
drop policy if exists expert_orders_own on public.expert_orders;
create policy expert_orders_own on public.expert_orders for select to authenticated using (auth.uid() = user_id);

-- Admin profiles: a signed-in user may read only their own profile row
drop policy if exists expert_admin_profiles_self_select on public.expert_admin_profiles;
create policy expert_admin_profiles_self_select on public.expert_admin_profiles for select to authenticated using (id = auth.uid());

-- Subscribers: anon insert with consent only (no read — plain INSERT, treat 409 as "already subscribed")
drop policy if exists offer_sub_insert_anon on public.offer_subscribers;
create policy offer_sub_insert_anon on public.offer_subscribers for insert to anon with check (consent = true);

